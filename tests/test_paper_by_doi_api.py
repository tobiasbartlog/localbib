PDF_BYTES = b"%PDF-1.4 fake open-access pdf"


def _crossref(record=None):
    """CrossRef answers ``record`` (``None``: nothing known) for every DOI."""
    return patch.object(paper_ingest, "fetch_crossref_metadata", return_value=record)


def _row(db, paper_id):
    conn = db._connect()
    try:
        return dict(conn.execute("SELECT * FROM papers WHERE id = ?", (paper_id,)).fetchone())
    finally:
        conn.close()


def _work(doi, pdf_url="", **extra):
    return {
        "id": "https://openalex.org/W1",
        "doi": f"https://doi.org/{doi}",
        "title": extra.get("title", "OA Werk"),
        "authorships": [{"author": {"display_name": n}} for n in extra.get("authors", [])],
        "publication_year": extra.get("year"),
        "cited_by_count": 3,
        "referenced_works": [],
        "abstract_inverted_index": extra.get("abstract_index"),
        "best_oa_location": {"pdf_url": pdf_url, "landing_page_url": ""} if pdf_url else None,
        "open_access": {"oa_url": ""},
    }


def test_create_stores_metadata_and_origin(client, db):
    resp = client.post("/api/papers/by-doi", json={
        "doi": "https://doi.org/10.5555/Intake.1",
        "title": "Robotic clay printing", "authors": ["Doe, Jane", "Roe, Rob"],
        "year": 2026, "journal": "AiC", "abstract": "Ein Abstract.", "source": "trend-plugin",
    })
    assert resp.status_code == 200, resp.text
    body = resp.json()
    assert body["created"] is True
    assert body["pdf"] == "none"
    assert body["doi"] == "10.5555/intake.1"
    row = _row(db, body["paper_id"])
    assert row["title"] == "Robotic clay printing"
    assert row["authors"] == "Doe, Jane; Roe, Rob"
    assert row["year"] == 2026
    assert row["journal"] == "AiC"
    assert row["abstract"] == "Ein Abstract."
    assert row["doi"] == "10.5555/intake.1"
    assert row["import_source"] == "trend-plugin"
    assert row["filename"] == ""
    assert row["cite_key"]  # generated by add_paper


